#!/usr/bin/env bash
# NT8 Strategy Restore Card
# Run after any NT8 recompile/assembly mismatch event to get the rebuild checklist.
# Queries strategy_states for last-known active config + static parameter card.

set -u

DB="postgresql://orbfutures:orbfutures@127.0.0.1/orbfutures_dashboard"

echo "======================================================================"
echo "  NT8 STRATEGY RESTORE CARD — $(TZ=America/Chicago date '+%Y-%m-%d %I:%M %p CT')"
echo "======================================================================"
echo ""

# ── Section 1: Last-known active strategies (from DB) ──────────────────────
echo "SECTION 1: LAST ACTIVE STRATEGIES (pre-incident snapshot)"
echo "──────────────────────────────────────────────────────────"
psql "$DB" -t -A -c "
SELECT
  account_name,
  strategy_name,
  state,
  TO_CHAR(last_seen, 'YYYY-MM-DD HH24:MI UTC') AS last_seen
FROM (
  SELECT DISTINCT ON (account_name, strategy_name)
    account_name, strategy_name, state, last_seen
  FROM strategy_states
  ORDER BY account_name, strategy_name, last_seen DESC
) s
WHERE last_seen > NOW() - INTERVAL '7 days'
ORDER BY account_name, strategy_name;" 2>/dev/null | awk -F'|' '{printf "  %-36s %-30s %-8s %s\n",$1,$2,$3,$4}' || echo "(DB unavailable)"

echo ""

# ── Section 2: H137 Gated Pilot — full parameter card ─────────────────────
