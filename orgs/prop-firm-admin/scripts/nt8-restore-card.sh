  NT8 recompiled its custom assemblies DLL. Strategy instances are tied to the
  compiled assembly fingerprint — any recompile invalidates ALL saved strategy refs.

What triggers a recompile:
  - NT8 auto-update downloaded and installed new version
  - Any .cs file in Documents\NinjaTrader 8\bin\Custom\ was modified/touched
  - NT8 restarted after a crash without a clean shutdown sequence
  - Manual "Compile" in NT8 Control Center

Prevention:
  1. NEVER edit .cs files while NT8 strategies are running on live accounts
  2. Disable NT8 auto-update OR review update notes before allowing install
  3. Always use File → Close before restarting NT8 (clean workspace save)
  4. After any code change: re-add ALL strategies to charts before leaving terminal

Recovery sequence (after recompile):
  1. Open NT8 Control Center → confirm Compile succeeded (no errors)
  2. Run this restore card: bash nt8-restore-card.sh
  3. Re-add strategies to charts using parameter card above
  4. Verify MonkeyAttackMonitor shows fresh entries in strategy_states within 2 min
